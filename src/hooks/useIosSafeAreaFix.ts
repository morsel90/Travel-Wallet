import { useEffect } from 'react'

// ─── useIosSafeAreaFix ──────────────────────────────────────────────────────
// 🐛 علة معروفة في iOS Safari (وضع PWA standalone تحديداً): قيمة
// env(safe-area-inset-top) لا تُحتسَب بشكل صحيح عند أول رسم لعنصر يحمل هذه
// الخاصية، وتبقى صفراً حتى يقع أول تمرير حقيقي من المستخدم. أي شاشة قصيرة بما
// يكفي لألا تحتاج تمريراً (TripPicker بقائمة رحلتين مثلاً) تبقى حشوتها
// العلوية صفراً للأبد فيتداخل هيدرها مع شريط الحالة/الشقّ (notch) — بخلاف
// شاشة طويلة يُمرّرها المستخدم عفواً فتُصحَّح صدفة.
//
// ⚠️ لا يكفي إصلاح واحد عند إقلاع التطبيق: التبديل بين الرحلة المفتوحة و
// «رحلاتي» عبر picker.show (تبديل حالة React بحت، بلا إعادة تحميل — انظر
// useAppCoordinator.ts) يُدرِج هيدر TripPicker كعنصر DOM *جديد* في كل مرة،
// فيعاني العلة نفسها من جديد رغم أن الصفحة نفسها لم تُعَد تحميلها إطلاقاً.
// لذا يُستدعى هذا الخطاف من كل مكوّن يحمل pt-[env(safe-area-inset-top)] على
// هيدره (Header.tsx وTripPicker.tsx)، ليُحاكي التمرير عند كل تركيب (mount) —
// لا مرة واحدة فقط عند إقلاع التطبيق.
//
// 🐛 محاولة أولى بلا هذا الحشو فشلت تحديداً على TripPicker: window.scrollTo
// لا يُحرِّك شيئاً إن كانت الصفحة لا تفيض عن الشاشة أصلاً (قائمة برحلتين تكفيها
// شاشة واحدة بلا تمرير) — فالتمرير المُحاكى كان بلا أثر تماماً هناك، بخلاف
// شاشة التطبيق الكامل الطويلة حيث يُحرِّك شيئاً فعلاً. لذا نفرض حشوة سفلية
// اصطناعية مؤقتة على body تضمن وجود ما يُمرَّر إليه دائماً، بصرف النظر عن طول
// محتوى الشاشة الحالية، ثم نُزيلها فور اكتمال المحاكاة.
export function useIosSafeAreaFix(): void {
  useEffect(() => {
    const originalMinHeight = document.body.style.minHeight
    document.body.style.minHeight = 'calc(100vh + 1px)'

    window.scrollTo(0, 1)
    requestAnimationFrame(() => {
      window.scrollTo(0, 0)
      document.body.style.minHeight = originalMinHeight
    })
  }, [])
}
