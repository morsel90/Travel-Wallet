/** الفئة الافتراضية حين لا يتطابق شيء — "أخرى"، آخر عنصر في القائمة (انظر constants.ts). */
export const FALLBACK_CATEGORY = EXPENSE_CATEGORIES[EXPENSE_CATEGORIES.length - 1]

/**
 * يُرجع فئة مقترَحة لوصف مصروف، أو "أخرى" إن لم يتطابق شيء.
 *
 * عند تطابق أكثر من مفتاح تفوز الكلمة الأطول — "سوبرماركت" (طعام وشراب) أدقّ من
 * "سوق" (تسوق) داخل النص نفسه، والأطول هو الأكثر تحديداً دائماً تقريباً.
 */
export function guessCategory(description: string): string {
  const text = normalize(description)
  if (!text.trim()) return FALLBACK_CATEGORY

  let best = FALLBACK_CATEGORY
  let bestLength = 0

  for (const [category, words] of Object.entries(KEYWORDS)) {
    for (const word of words) {
      if (word.length > bestLength && text.includes(normalize(word))) {
        best = category
        bestLength = word.length
      }
    }
  }

  return best
}
