// 🆕 أدوات اسم المسافر ومعرّفه — دوال بحتة قابلة للاختبار (انظر travelerName.test.ts).
//
// الاسم المختصر يُستخدم لغرضين مختلفين تماماً:
//   1. مطابقة المشاركين في المصاريف القديمة (انظر utils/participants.ts)
//   2. 🆕 معرّف مستند حجز الاسم travelerNames/{shortName} الذي يفرض التفرّد
// الغرض الثاني هو سبب وجود isValidNameKey: ما يصلح للعرض لا يصلح بالضرورة
// معرّفَ مستند في Firestore.

/**
 * الاسم المختصر = أول كلمة من الاسم الكامل. نقسّم على أي مسافة بيضاء (لا على
 * ' ' وحدها) حتى لا ينتج اسم فارغ من مسافات متتالية أو مسافة غير معتادة
 * ملصوقة من مكان آخر — وهي شائعة في الأسماء المنسوخة.
 */
export function deriveShortName(fullName: string): string {
  return fullName.trim().split(/\s+/)[0] ?? ''
}

/**
 * هل يصلح هذا الاسم معرّفَ مستند في Firestore؟ القيود مفروضة من Firestore نفسه:
 *   - لا يكون فارغاً
 *   - لا يحوي شرطة مائلة (تفصل مقاطع المسار فتُنشئ مستنداً في مكان آخر)
 *   - لا يكون "." أو ".." (لهما معنى خاص في المسارات)
 *   - لا يطابق __*__ (نمط محجوز لـ Firestore)
 *   - لا يتجاوز 1500 بايت — نتحقق بالبايتات لا بالمحارف، فالحرف العربي بايتان
 *     في UTF-8 وحدّ المحارف كان سيسمح بتجاوز الحدّ الفعلي.
 * عملياً لن يقترب اسم شخص من هذه الحدود، لكن الفحص يمنع تحوّل اسم غريب من
 * رسالة خطأ مفهومة إلى فشل كتابة غامض عند المزامنة.
 */
export function isValidNameKey(shortName: string): boolean {
  if (!shortName) return false
  if (shortName.includes('/')) return false
  if (shortName === '.' || shortName === '..') return false
  if (/^__.*__$/.test(shortName)) return false
  return new TextEncoder().encode(shortName).length <= 1500
}

/**
 * معرّف مسافر عشوائي.
 *
 * ⚠️ كان يُحسب سابقاً كـ «أكبر معرّف + 1» على العميل. مسؤولان يضيفان مسافرَين
 * في نفس اللحظة يحصلان على نفس الرقم، ويكتب الثاني فوق الأول (setDoc على مستند
 * قائم كتابة فوقية، والقواعد تسمح بها للمسؤول) — فيختفي مسافر ورصيده المودَع
 * بصمت. العشوائية تُلغي هذا عملياً: في مدى ~2.1 مليار، احتمال التصادم بين 50
 * مسافراً أقل من واحد في المليون.
 *
 * المدى موجب وأقل من 2^31 ليبقى int صالحاً في firestore.rules (d.id is int).
 */
export function newTravelerId(): number {
  const bytes = new Uint32Array(1)
  crypto.getRandomValues(bytes)
  return (bytes[0] % 2_147_483_646) + 1
}
