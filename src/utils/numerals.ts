// 🆕 تحويل الأرقام الهندية/الشرقية (١٢٣) إلى غربية (123).
//
// ⚠️ **كانت هذه الدالة منسوخة حرفياً في ملفين** — `DepositModal.tsx` (حُذف حين
// صار تعديل الرصيد قسماً مضمّناً داخل ملف المسافر) و`TravelerSection.tsx`.
// نسخة واحدة هنا بدل نسختين: القاعدة ٨ (منطق نقي في `utils/`، قابل للاختبار
// بلا React ولا DOM) والقاعدة ٩ (تحويل الأرقام العربية جزء من كون التطبيق
// عربياً أولاً، لا تفصيلاً في حقل بعينه).
//
// ⚠️ لا يُصفّي غير الأرقام ولا يتحقّق من صحّة العدد — ذاك شأن الحقل الذي
// يستدعيه (لكلٍّ قواعده: عشريّة، سالب، طول أقصى)، وهذه تفعل شيئاً واحداً.
const EASTERN_TO_WESTERN: Record<string, string> = {
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
  '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
}

export const toWesternDigits = (input: string): string =>
  input.replace(/[٠-٩]/g, ch => EASTERN_TO_WESTERN[ch] ?? ch)

/** تحويل + تصفية إلى مبلغ عشري صالح للكتابة في حقل نصّي (نقطة عشرية واحدة).
 *
 * ⚠️ **الفاصلة العشرية العربية (٫ = U+066B) تُترجَم إلى نقطة هنا، ولم تكن.**
 * لوحة المفاتيح العربية تُخرجها لا النقطة، وكلا النسختين المنسوختين سابقاً
 * كانتا تُسقطانها مع بقية «ما ليس رقماً» — فيصير «٥٠٫٥» المبلغَ `505`، أي
 * خطأً بعشرة أضعاف في حقل مالي، بصمت وبلا أي رسالة. القاعدة ١٩ تضع التحقّق
 * عند الحدّ، وهذا هو الحدّ. (النقطة العادية تبقى مقبولة كما كانت.) */
export const sanitizeAmountInput = (input: string): string => {
  const digitsOnly = toWesternDigits(input).replace(/٫/g, '.').replace(/[^0-9.]/g, '')
  const parts = digitsOnly.split('.')
  return parts.length > 2 ? `${parts[0]}.${parts.slice(1).join('')}` : digitsOnly
}
