// 🆕 تحميل مسبق هادئ للأجزاء المؤجّلة (React.lazy) بعد أن يصبح التطبيق تفاعلياً.
//
// ⚠️ المشكلة التي يعالجها — كشفها اختبار E2E فعلياً لا افتراضاً:
// الأجزاء المُحمَّلة بـ React.lazy لا تُطلب من الشبكة إلا لحظة الحاجة إليها أول
// مرة. فإذا وقعت تلك اللحظة والمستخدم بلا اتصال، فشل الاستيراد الديناميكي ورمى
// خطأً أثناء العرض، فتنهار الشجرة إلى ErrorBoundary وتُستبدل الواجهة كاملةً
// بشاشة «حدث خطأ غير متوقع». الحالة الأوضح: أول مصروف يُسجَّل في الرحلة يستدعي
// ChartsSection لأول مرة (activeExpenses.length > 0)، فتسجيله أثناء انقطاع
// الاتصال كان يُسقط التطبيق بالكامل.
//
// في الإنتاج يغطّي Service Worker هذا (generateSW يخزّن كل ملفات js مسبقاً —
// انظر globPatterns في vite.config.js)، لكن تبقى نافذة زمنية حقيقية: زيارة
// أولى ينقطع فيها الاتصال قبل أن يكتمل تفعيل الـ SW وتخزينه للحزم.
//
// ⚠️ لماذا «هادئ» تحديداً: هذه الأجزاء مؤجّلة عمداً لتخفيف الحزمة الأولى، فسحبها
// مبكراً يُبطل الغرض. لذا لا يبدأ السحب إلا بعد أن يفرغ الخيط الرئيسي
// (requestIdleCallback)، فلا ينافس أول عرض ولا تفاعل المستخدم.
//
// ⚠️ الفشل هنا لا يُبلَّغ عنه ولا يُعالَج بإعادة محاولة: هذا تحسين انتهازي بحت.
// إن فشل السحب المسبق (انقطاع، أو حظر) يبقى السلوك كما كان تماماً — يُطلب الجزء
// عند الحاجة. ولهذا كل الوعود تُبتلع أخطاؤها صراحةً: وعد مرفوض بلا معالج يُنتج
// unhandledrejection في الكونسول بلا أي فائدة تشخيصية.

/** يجدول عملاً حتى يفرغ الخيط الرئيسي، مع بديل لمتصفحات بلا requestIdleCallback (أبرزها Safari الأقدم). */
export function onIdle(task: () => void, fallbackDelayMs = 2000): () => void {
  if (typeof window === 'undefined') return () => {}

  const ric = (window as unknown as {
    requestIdleCallback?: (cb: () => void, opts?: { timeout: number }) => number
    cancelIdleCallback?: (id: number) => void
  })

  if (typeof ric.requestIdleCallback === 'function') {
    // timeout يضمن التنفيذ ولو بقي الخيط مشغولاً — بلا سقف قد لا يأتي وقت خمول أبداً
    const id = ric.requestIdleCallback(task, { timeout: 5000 })
    return () => ric.cancelIdleCallback?.(id)
  }

  const id = window.setTimeout(task, fallbackDelayMs)
  return () => window.clearTimeout(id)
}

/**
 * يبدأ سحب مجموعة أجزاء مؤجّلة دون انتظار نتيجتها.
 *
 * تُمرَّر نفس دوال الاستيراد المستخدَمة في `lazy()` حرفياً — وهذا شرط صحة لا
 * تفصيل أسلوبي: المتصفح (وVite) يوحّدان الوحدة بمُعرّفها، فأي اختلاف في المسار
 * يعني سحب وحدة أخرى وبقاء الأصلية بلا تحميل مسبق. لهذا تُصدَّر دوال التحميل
 * المسبق من نفس الملفات التي تُعرّف `lazy()` وبجوارها مباشرةً.
 */
export function preloadAll(importers: Array<() => Promise<unknown>>): void {
  for (const load of importers) {
    // ابتلاع صريح: انظر التعليق أعلى الملف
    try {
      void load().catch(() => {})
    } catch {
      // استيراد قد يرمي تزامنياً في بيئات نادرة — لا يجوز أن يُسقط المستدعي
    }
  }
}
